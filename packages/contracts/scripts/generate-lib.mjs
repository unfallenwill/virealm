// Bundles the modular JSON Schemas into one Draft 2020-12 document, then
// derives the committed TypeScript types, schema literal and enum constants.
//
// The generator is deliberately small and deterministic: no network, no
// timestamps, sorted definitions, LF line endings.

import { readFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";

const PACKAGE_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS_DIR = join(PACKAGE_ROOT, "schemas");
const ENTRY_SCHEMA = join(SCHEMAS_DIR, "index.schema.json");

const GENERATED_DIR = join(PACKAGE_ROOT, "src", "generated");
export const OUTPUT_FILES = {
  types: join(GENERATED_DIR, "protocol.ts"),
  schema: join(GENERATED_DIR, "schemas.ts"),
  constants: join(GENERATED_DIR, "constants.ts"),
};

const BANNER = `/**
 * Generated by scripts/generate.mjs from the JSON Schemas in schemas/.
 * Do not edit this file by hand. Run \`pnpm generate\` instead.
 */`;

const TYPE_DEF_PATTERN = /^#?\/\$defs\/([A-Za-z][A-Za-z0-9]*)$/;

async function readJson(file) {
  return JSON.parse(await readFile(file, "utf8"));
}

class SchemaBundler {
  constructor(entryFile) {
    this.entryFile = entryFile;
    this.documents = new Map();
    this.definitions = new Map();
    this.definitionSources = new Map();
    this.inProgress = new Set();
  }

  async load(file) {
    let document = this.documents.get(file);
    if (document === undefined) {
      document = await readJson(file);
      this.documents.set(file, document);
    }
    return document;
  }

  async bundle() {
    const entry = await this.load(this.entryFile);
    const root = await this.rewriteNode(entry, this.entryFile);

    // x-include is a generation manifest, not a validation keyword. It lets
    // the entry point pull in definitions that are public constants without
    // making them valid standalone messages.
    const includes = Array.isArray(root["x-include"]) ? root["x-include"] : [];
    delete root["x-include"];
    for (const ref of includes) {
      if (typeof ref !== "string") {
        throw new Error("x-include entries must be $ref strings.");
      }
      await this.resolveRef(ref, this.entryFile);
    }

    const definitions = Object.fromEntries(
      [...this.definitions.entries()].sort(([left], [right]) =>
        left.localeCompare(right),
      ),
    );
    return { ...root, $defs: definitions };
  }

  async rewriteNode(node, file) {
    if (Array.isArray(node)) {
      return Promise.all(node.map((item) => this.rewriteNode(item, file)));
    }
    if (node === null || typeof node !== "object") {
      return node;
    }
    if (typeof node.$ref === "string") {
      const target = await this.resolveRef(node.$ref, file);
      return { ...node, $ref: target };
    }

    const rewritten = {};
    for (const [key, value] of Object.entries(node)) {
      if (key === "$defs" || key === "definitions") {
        continue;
      }
      rewritten[key] = await this.rewriteNode(value, file);
    }
    return rewritten;
  }

  async resolveRef(ref, fromFile) {
    const hashIndex = ref.indexOf("#");
    const pathPart = hashIndex === -1 ? ref : ref.slice(0, hashIndex);
    const pointer = hashIndex === -1 ? "" : ref.slice(hashIndex + 1);
    const targetFile =
      pathPart === "" ? fromFile : resolve(dirname(fromFile), pathPart);

    const match = TYPE_DEF_PATTERN.exec(pointer);
    if (match === null) {
      throw new Error(
        `Unsupported $ref "${ref}" in ${fromFile}; only "#/$defs/Name" pointers are allowed.`,
      );
    }
    const name = match[1];
    const sourceKey = `${targetFile}#${pointer}`;
    const previousSource = this.definitionSources.get(name);
    if (previousSource !== undefined && previousSource !== sourceKey) {
      throw new Error(
        `Schema name "${name}" is defined twice: ${previousSource} and ${sourceKey}. ` +
          "Every definition name must be unique across files.",
      );
    }
    if (this.inProgress.has(sourceKey)) {
      return `#/$defs/${name}`;
    }
    if (this.definitions.has(name)) {
      return `#/$defs/${name}`;
    }

    const document = await this.load(targetFile);
    const definition = document.$defs?.[name];
    if (definition === undefined) {
      throw new Error(`Missing definition "${name}" in ${targetFile}.`);
    }

    this.definitionSources.set(name, sourceKey);
    this.inProgress.add(sourceKey);
    this.definitions.set(name, await this.rewriteNode(definition, targetFile));
    this.inProgress.delete(sourceKey);
    return `#/$defs/${name}`;
  }
}

// json-schema-to-typescript 16 reads `definitions`, not 2020-12 `$defs`.
// The emitted declarations are identical; only the pointer spelling changes.
export function toCodegenSchema(schema) {
  const rewrite = (node) => {
    if (Array.isArray(node)) {
      return node.map(rewrite);
    }
    if (node === null || typeof node !== "object") {
      return node;
    }
    const output = {};
    for (const [key, value] of Object.entries(node)) {
      output[key] =
        key === "$ref" && typeof value === "string"
          ? value.replace("#/$defs/", "#/definitions/")
          : rewrite(value);
    }
    return output;
  };

  const { $defs: definitions, ...root } = schema;
  const converted = rewrite(root);
  converted.definitions = rewrite(definitions ?? {});
  return converted;
}

function readConst(schema, name, property) {
  const definition = schema.$defs[name];
  if (definition === undefined) {
    throw new Error(`Expected definition "${name}" in the bundled schema.`);
  }
  const value = definition[property];
  if (value === undefined) {
    throw new Error(`Definition "${name}" has no ${property}.`);
  }
  return value;
}

function readEnum(schema, name) {
  return readConst(schema, name, "enum");
}

function readEventNames(schema) {
  const eventUnion = schema.$defs.Event;
  if (eventUnion === undefined || !Array.isArray(eventUnion.oneOf)) {
    throw new Error('Expected "$defs.Event" to be a oneOf union.');
  }
  return eventUnion.oneOf
    .map((variant) => {
      const match = TYPE_DEF_PATTERN.exec(variant.$ref ?? "");
      if (match === null) {
        throw new Error(
          `Event variant is not a local $defs reference: ${JSON.stringify(variant)}`,
        );
      }
      const definition = schema.$defs[match[1]];
      const value = definition?.properties?.event?.const;
      if (typeof value !== "string") {
        throw new Error(
          `Event definition "${match[1]}" has no const event name.`,
        );
      }
      return value;
    })
    .sort();
}

function literalList(values) {
  return values.map((value) => JSON.stringify(value)).join(", ");
}

function renderConstants(schema) {
  const protocolVersion = readConst(schema, "ProtocolVersion", "const");
  const methodNames = readEnum(schema, "MethodName");
  const errorCodes = readEnum(schema, "ErrorCode");
  const capabilityStates = readEnum(schema, "CapabilityState");
  const isolationModes = readEnum(schema, "IsolationMode");
  const networkAccessValues = readEnum(schema, "NetworkAccess");
  const integrityLevels = readEnum(schema, "IntegrityLevel");
  const diagnosticLevels = readEnum(schema, "DiagnosticLevel");
  const eventNames = readEventNames(schema);

  return `/* eslint-disable */
${BANNER}

export const PROTOCOL_VERSION = ${JSON.stringify(protocolVersion)} as const;

export const METHOD_NAMES = [${literalList(methodNames)}] as const;

export const ERROR_CODES = [${literalList(errorCodes)}] as const;

export const CAPABILITY_STATES = [${literalList(capabilityStates)}] as const;

export const ISOLATION_MODES = [${literalList(isolationModes)}] as const;

export const NETWORK_ACCESS_VALUES = [${literalList(networkAccessValues)}] as const;

export const INTEGRITY_LEVELS = [${literalList(integrityLevels)}] as const;

export const DIAGNOSTIC_LEVELS = [${literalList(diagnosticLevels)}] as const;

export const EVENT_NAMES = [${literalList(eventNames)}] as const;
`;
}

function renderSchema(schema) {
  return `/* eslint-disable */
${BANNER}

import type { JsonSchema } from "../json-schema.js";

export const VIREALM_SCHEMA_ID = ${JSON.stringify(schema.$id)};

export const virealmSchema: JsonSchema = ${JSON.stringify(schema, null, 2)};

export default virealmSchema;
`;
}

export async function bundleSchemas() {
  return new SchemaBundler(ENTRY_SCHEMA).bundle();
}

export async function renderGeneratedFiles() {
  const bundled = await bundleSchemas();

  const types = await compile(toCodegenSchema(bundled), "VirealmProtocol", {
    additionalProperties: false,
    bannerComment: `/* eslint-disable */\n${BANNER}`,
    declareExternallyReferenced: true,
    enableConstEnums: false,
    format: false,
    ignoreMinAndMaxItems: true,
    strictIndexSignatures: true,
    unreachableDefinitions: true,
    unknownAny: true,
  });

  return new Map([
    [OUTPUT_FILES.types, `${types.trimEnd()}\n`],
    [OUTPUT_FILES.schema, renderSchema(bundled)],
    [OUTPUT_FILES.constants, renderConstants(bundled)],
  ]);
}
